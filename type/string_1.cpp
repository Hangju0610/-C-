#include <bits/stdc++.h>
using namespace std;
int main() {
    string a = "나는야";
    cout << a[0] << "\n";
    cout << a[0] << a[1] << a[2] << "\n";
    cout << a << "\n";
    string b = "abc";
    cout << b[0] << "\n";
    cout << b[0] << b[1] << b[2] << "\n";
    cout << b << "\n";
    return 0;
}
